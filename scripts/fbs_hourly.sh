#!/usr/bin/env bash
#
# Почасовое обновление заказов FBS.
#
# Запускается из cron. Делает три вещи по порядку:
#
#   1. utils/load_fbs_orders.py   — забирает заказы, поставки
#                                   и справочники складов из API WB
#   2. manage.py fbs_orders_etl   — раскладывает заказы в DuckDB
#   3. manage.py fbs_dicts_etl    — раскладывает справочники
#
# Две вещи, ради которых существует этот скрипт, а не три
# строки в crontab:
#
#   flock — второй запуск не стартует, пока идёт первый.
#   Полная выгрузка идёт минутами, и если WB затормозит,
#   без блокировки в базу полезли бы два процесса разом.
#
#   Повтор при занятой базе — сайт читает ту же базу, в которую
#   пишет загрузка. Раз в час кто-то откроет страницу ровно
#   в момент записи и получит «Could not set lock». Ждём
#   и пробуем ещё раз, вместо того чтобы потерять обновление.
#

set -uo pipefail


# ============================================================
# НАСТРОЙКИ
# ============================================================

PROJECT_DIR="/home/daria/ts"

PYTHON="${PROJECT_DIR}/.venv/bin/python"

LOG_DIR="${PROJECT_DIR}/logs"
LOG_FILE="${LOG_DIR}/fbs_hourly.log"

LOCK_FILE="/tmp/fbs_hourly.lock"

# Сколько раз повторять шаг, упавший из-за занятой базы,
# и сколько ждать между попытками.
MAX_ATTEMPTS=3
RETRY_PAUSE=20

# Сколько строк лога хранить.
LOG_KEEP_LINES=20000


# ============================================================
# ЛОГ
# ============================================================

mkdir -p "${LOG_DIR}"

log() {
    echo "[$(date '+%Y-%m-%d %H:%M:%S %Z')] $*"
}


# ============================================================
# ЗАПУСК С ПОВТОРОМ ПРИ ЗАНЯТОЙ БАЗЕ
# ============================================================

run_step() {
    local title="$1"
    shift

    local attempt=1
    local output
    local status

    while true; do

        log "${title}: попытка ${attempt} из ${MAX_ATTEMPTS}"

        output="$("$@" 2>&1)"
        status=$?

        echo "${output}"

        if [ ${status} -eq 0 ]; then
            log "${title}: успешно"
            return 0
        fi

        # Повторяем только блокировку базы. Ошибка в данных
        # или в API от повтора не исправится — нет смысла
        # долбить WB ещё два раза.
        if ! echo "${output}" | grep -qi "lock"; then
            log "${title}: ОШИБКА (повтор не поможет)"
            return ${status}
        fi

        if [ ${attempt} -ge ${MAX_ATTEMPTS} ]; then
            log "${title}: база занята, попытки исчерпаны"
            return ${status}
        fi

        log "${title}: база занята, ждём ${RETRY_PAUSE} с"
        sleep ${RETRY_PAUSE}

        attempt=$(( attempt + 1 ))
    done
}


# ============================================================
# ОСНОВНАЯ РАБОТА
# ============================================================

main() {

    cd "${PROJECT_DIR}" || {
        log "Не найден каталог проекта: ${PROJECT_DIR}"
        return 1
    }

    if [ ! -x "${PYTHON}" ]; then
        log "Не найден python: ${PYTHON}"
        return 1
    fi

    log "=================================================="
    log "Запуск почасового обновления FBS"

    # --------------------------------------------------------
    # 1. Забираем данные из WB
    #
    # Повтор здесь не делаем: если API не ответил, через час
    # будет следующая попытка, а долбить его сразу же незачем.
    # --------------------------------------------------------

    if ! run_step \
        "Загрузка из API WB" \
        "${PYTHON}" utils/load_fbs_orders.py
    then
        log "Загрузка не удалась — таблицы не трогаем"
        log "Завершено с ошибкой"
        return 1
    fi

    # --------------------------------------------------------
    # 2. Заказы в DuckDB
    # --------------------------------------------------------

    if ! run_step \
        "Заказы в DuckDB" \
        "${PYTHON}" manage.py fbs_orders_etl
    then
        log "Завершено с ошибкой"
        return 1
    fi

    # --------------------------------------------------------
    # 3. Справочники складов
    #
    # Не критично: без них вкладка работает и показывает
    # номера складов вместо названий.
    # --------------------------------------------------------

    run_step \
        "Справочники складов" \
        "${PYTHON}" manage.py fbs_dicts_etl \
        || log "Справочники не обновились, продолжаем"

    log "Готово"

    return 0
}


# ============================================================
# ТОЧКА ВХОДА
#
# flock -n: если предыдущий запуск ещё идёт, молча выходим.
# Это нормальная ситуация, а не ошибка.
# ============================================================

{
    exec 9>"${LOCK_FILE}"

    if ! flock -n 9; then
        log "Предыдущий запуск ещё идёт — пропускаем"
        exit 0
    fi

    main
    exit_code=$?

    # Подрезаем лог, чтобы он не рос бесконечно.
    if [ -f "${LOG_FILE}" ]; then
        tail -n ${LOG_KEEP_LINES} "${LOG_FILE}" > "${LOG_FILE}.tmp" \
            && mv "${LOG_FILE}.tmp" "${LOG_FILE}"
    fi

    exit ${exit_code}

} >> "${LOG_FILE}" 2>&1
