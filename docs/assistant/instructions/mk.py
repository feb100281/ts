import math
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.worksheet.page import PageMargins

G, GD, GL, GS = "2F6656", "1F5E4E", "E7F1ED", "F7F9F8"
TXT, MUT, LINE, WARN, WARNBG = "1F1F1F", "6B7280", "D9DEDC", "7B4437", "F6E9E4"
F = "Arial"
def font(sz=10, b=False, c=TXT, i=False): return Font(name=F, size=sz, bold=b, color=c, italic=i)
def fill(c): return PatternFill("solid", fgColor=c)
thin = Side(style="thin", color=LINE)
WRAP = Alignment(wrap_text=True, vertical="top")
MID = Alignment(wrap_text=True, vertical="center")

def height(texts_widths, base=15.5, pad=7):
    n = 1
    for t, w in texts_widths:
        cpl = max(8, int(w * 1.0))
        lines = sum(max(1, math.ceil(len(p) / cpl)) for p in str(t).split("\n"))
        n = max(n, lines)
    return n * base + pad

class Sheet:
    def __init__(s, wb, title, widths, first=False):
        s.ws = wb.active if first else wb.create_sheet()
        s.ws.title = title
        s.ws.sheet_view.showGridLines = False
        s.w = widths
        for col, w in zip("ABCDEFG", [2] + widths + [2]):
            s.ws.column_dimensions[col].width = w
        s.n = len(widths); s.r = 1
        s.ws.page_setup.orientation = "portrait"; s.ws.page_setup.paperSize = 9
        s.ws.page_setup.fitToWidth = 1; s.ws.page_setup.fitToHeight = 0
        s.ws.sheet_properties.pageSetUpPr.fitToPage = True
        s.ws.page_margins = PageMargins(0.4, 0.4, 0.5, 0.5)
    def last(s): return 1 + s.n
    def merge(s, r): 
        if s.n > 1: s.ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=s.last())
    def band(s, title, sub):
        ws = s.ws
        for r, h in ((1, 8), (2, 34), (3, 20), (4, 10)):
            ws.row_dimensions[r].height = h
            for c in range(1, s.last() + 2): ws.cell(r, c).fill = fill(G)
        s.merge(2); s.merge(3)
        c = ws.cell(2, 2, title); c.font = font(18, True, "FFFFFF"); c.alignment = Alignment(vertical="center")
        c = ws.cell(3, 2, sub); c.font = font(10, False, "D5E5DF"); c.alignment = Alignment(vertical="center")
        ws.row_dimensions[5].height = 10; s.r = 6
    def h(s, num, text):
        ws = s.ws; ws.row_dimensions[s.r].height = 8; s.r += 1
        s.merge(s.r)
        c = ws.cell(s.r, 2, f"{num:02d}   {text.upper()}"); c.font = font(10.5, True, GD)
        c.alignment = Alignment(vertical="center", indent=1)
        for col in range(2, s.last() + 1):
            ws.cell(s.r, col).fill = fill(GL)
            ws.cell(s.r, col).border = Border(top=Side(style="medium", color=G))
        ws.row_dimensions[s.r].height = 24; s.r += 1
    def p(s, text, bold=False, tone=None):
        ws = s.ws; s.merge(s.r)
        c = ws.cell(s.r, 2, text); c.alignment = Alignment(wrap_text=True, vertical="center", indent=1)
        c.font = font(10, bold, WARN if tone == "warn" else TXT)
        if tone:
            for col in range(2, s.last() + 1):
                ws.cell(s.r, col).fill = fill(WARNBG if tone == "warn" else GS)
        ws.row_dimensions[s.r].height = height([(text, sum(s.w) - 2)], pad=9); s.r += 1
    def bullets(s, items):
        for t in items:
            ws = s.ws; s.merge(s.r)
            c = ws.cell(s.r, 2, "■  " + t); c.font = font(10); 
            c.alignment = Alignment(wrap_text=True, vertical="center", indent=1)
            for col in range(2, s.last() + 1): ws.cell(s.r, col).border = Border(bottom=thin)
            ws.row_dimensions[s.r].height = height([(t, sum(s.w) - 5)], pad=8); s.r += 1
    def table(s, header, rows, bold_first=True):
        ws = s.ws
        for i, t in enumerate(header):
            c = ws.cell(s.r, 2 + i, t.upper()); c.font = font(9, True, "FFFFFF"); c.fill = fill(G)
            c.alignment = Alignment(vertical="center", wrap_text=True, indent=1)
        ws.row_dimensions[s.r].height = 22; s.r += 1
        for k, row in enumerate(rows):
            for i, t in enumerate(row):
                c = ws.cell(s.r, 2 + i, t)
                c.font = font(10, bold_first and i == 0, GD if (bold_first and i == 0) else TXT)
                c.alignment = Alignment(wrap_text=True, vertical="center", indent=1)
                c.border = Border(bottom=thin)
                if k % 2: c.fill = fill(GS)
            ws.row_dimensions[s.r].height = height([(t, s.w[i] - 2) for i, t in enumerate(row)], pad=9)
            s.r += 1
    def gap(s, h=6): s.ws.row_dimensions[s.r].height = h; s.r += 1
    def foot(s, text):
        s.gap(10); s.merge(s.r)
        c = s.ws.cell(s.r, 2, text); c.font = font(8.5, False, MUT, True); s.r += 1

