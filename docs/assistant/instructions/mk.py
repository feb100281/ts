def build(path, cfg):
    wb = Workbook()
    s = Sheet(wb, "Инструкция", [30, 44, 44], first=True)
    s.band(cfg["title"], cfg["sub"])
    s.h(1, "Что это и где найти"); [s.p(t) for t in cfg["what"]]
    s.h(2, "Как задать вопрос"); s.table(["Шаг", "Что сделать", "Подсказка"], cfg["steps"])
    s.h(3, cfg["two_title"]); s.p(cfg["two_lead"])
    s.table(["", "Как на сайте WB", "Управленческие (мэн пак)"], cfg["two"])
    s.gap(); s.p(cfg["two_tip"], tone="info")
    s.h(4, "Что умеет помощник"); s.table(["Тема", "Что можно спросить", "Пример вопроса"], cfg["can"])
    s.h(5, "Выгрузки в Excel"); [s.p(t) for t in cfg["excel"]]; s.bullets(cfg["excel_ex"])
    s.h(6, "Чего помощник не делает"); s.bullets(cfg["cant"])
    s.h(7, "Если помощник ошибся"); s.p(CONTACT, bold=True, tone="warn"); s.gap(4)
    s.p("Что прислать:"); s.bullets(SEND)
    s.foot("Помощник работает в тестовом режиме. Важные цифры перед отправкой руководству сверяйте с дашбордом.")
    s.ws.freeze_panes = "A6"

    q = Sheet(wb, "Примеры вопросов", [8, 62, 48])
    q.band("Примеры вопросов", "Можно копировать и менять период, бренд или контрагента")
    n = 0
    for grp, items in cfg["examples"]:
        n += 1; q.h(n, grp)
        q.table(["№", "Вопрос", "Что получите"], [[str(i + 1), a, b] for i, (a, b) in enumerate(items)], bold_first=False)
    q.foot("Пишите своими словами — точные формулировки не обязательны. Главное — период и что именно посчитать.")
    q.ws.freeze_panes = "A6"
    wb.save(path)

