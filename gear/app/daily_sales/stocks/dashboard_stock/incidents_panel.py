"""Панель происшествий на основной странице dashboard."""

from __future__ import annotations

import pandas as pd
import dash_mantine_components as dmc

from dash import html

from ..dashboard_data import (
    get_warehouse_incident_snapshot,
)

from .warehouse_incidents import (
    WAREHOUSE_INCIDENTS,
)

from .helpers import (
    fmt,
    fmt_money,
)


TEXT = "#18352F"
MUTED = "#60746D"

BORDER = "#D6DFDB"
INCIDENT_BORDER = "#E2CACA"
INCIDENT_ACCENT = "#A43E3E"
INCIDENT_BG = "#FFFDFD"


# =============================================================================
# КАРТОЧКА ПРОИСШЕСТВИЯ
# =============================================================================


def _incident_card(
    warehouse_name: str,
    incident: dict,
):
    """
    Карточка одного происшествия.

    incident["date"] — фактическая дата происшествия.

    Для финансовой оценки используется исторический
    снимок склада на ПРЕДЫДУЩИЙ календарный день.

    Например:
        происшествие: 22.07.2026
        снимок:       21.07.2026

    Для события рассчитываются:

    - физический остаток;
    - количество NM ID;
    - бухгалтерская стоимость;
    - управленческая стоимость.

    Товар в пути в оценку происшествия не включается.
    """

    # =========================================================================
    # Дата самого происшествия
    # =========================================================================

    incident_date = pd.to_datetime(
        incident["date"]
    )

    event_date = incident_date.strftime(
        "%d.%m.%Y"
    )

    # =========================================================================
    # Дата снимка
    #
    # Остатки берём на конец дня,
    # предшествующего происшествию.
    # =========================================================================

    requested_snapshot_date = (
        incident_date
        - pd.Timedelta(days=1)
    )

    # =========================================================================
    # Исторический снимок склада
    # =========================================================================

    snapshot = (
        get_warehouse_incident_snapshot(
            warehouse_name=warehouse_name,
            incident_date=(
                requested_snapshot_date.strftime(
                    "%Y-%m-%d"
                )
            ),
        )
    )

    # =========================================================================
    # Фактическая дата снимка остатков
    # =========================================================================

    effective_date = snapshot.get(
        "effective_date"
    )

    snapshot_label = (
        pd.to_datetime(
            effective_date
        ).strftime(
            "%d.%m.%Y"
        )
        if effective_date
        else "нет данных"
    )

    # =========================================================================
    # Карточка
    # =========================================================================

    return dmc.Paper(
        radius=0,

        p="lg",

        style={
            "border": (
                f"1px solid {INCIDENT_BORDER}"
            ),

            "borderLeft": (
                f"4px solid {INCIDENT_ACCENT}"
            ),

            "background": INCIDENT_BG,

            # Карточка не должна сжиматься
            # внутри scroll-контейнера.
            "flexShrink": 0,
        },

        children=[

            # =================================================================
            # HEADER
            # =================================================================

            dmc.Group(
                justify="space-between",

                align="flex-start",

                gap="md",

                children=[

                    # ---------------------------------------------------------
                    # Название склада / событие
                    # ---------------------------------------------------------

                    html.Div(
                        style={
                            "minWidth": 0,
                        },

                        children=[

                            dmc.Group(
                                gap=8,

                                children=[

                                    dmc.Text(
                                        warehouse_name,

                                        fw=700,

                                        size="md",

                                        c=TEXT,
                                    ),

                                    dmc.Badge(
                                        incident.get(
                                            "status",
                                            "Происшествие",
                                        ),

                                        color="red",

                                        variant="light",

                                        radius=0,
                                    ),
                                ],
                            ),

                            dmc.Text(
                                (
                                    f"{incident.get('title', 'Происшествие')} "
                                    f"· {event_date}"
                                ),

                                size="sm",

                                c=MUTED,

                                mt=2,
                            ),
                        ],
                    ),

                    # ---------------------------------------------------------
                    # Дата снимка
                    # ---------------------------------------------------------

                    dmc.Text(
                        (
                            "Остатки на: "
                            f"{snapshot_label}"
                        ),

                        size="xs",

                        c="dimmed",

                        style={
                            "whiteSpace": "nowrap",
                        },
                    ),
                ],
            ),

            # =================================================================
            # ОПИСАНИЕ
            # =================================================================

            dmc.Text(
                incident.get(
                    "description",
                    "",
                ),

                size="sm",

                c=TEXT,

                mt="md",
            ),

            # =================================================================
            # KPI СОБЫТИЯ
            # =================================================================

            dmc.SimpleGrid(
                cols={
                    "base": 2,
                    "sm": 4,
                },

                spacing="md",

                mt="lg",

                children=[

                    # ---------------------------------------------------------
                    # Физический остаток
                    # ---------------------------------------------------------

                    html.Div(
                        children=[

                            dmc.Text(
                                "Физический остаток",

                                size="xs",

                                c="dimmed",
                            ),

                            dmc.Text(
                                (
                                    f"{fmt(snapshot['on_hand'])} "
                                    "шт"
                                ),

                                fw=700,

                                size="lg",

                                c=TEXT,
                            ),
                        ],
                    ),

                    # ---------------------------------------------------------
                    # NM ID
                    # ---------------------------------------------------------

                    html.Div(
                        children=[

                            dmc.Text(
                                "Товаров",

                                size="xs",

                                c="dimmed",
                            ),

                            dmc.Text(
                                (
                                    f"{fmt(snapshot['nm_count'])} "
                                    "NM ID"
                                ),

                                fw=700,

                                size="lg",

                                c=TEXT,
                            ),
                        ],
                    ),

                    # ---------------------------------------------------------
                    # Бухгалтерская стоимость
                    # ---------------------------------------------------------

                    html.Div(
                        children=[

                            dmc.Text(
                                "Бухгалтерская с/с",

                                size="xs",

                                c="dimmed",
                            ),

                            dmc.Text(
                                (
                                    f"{fmt_money(
                                        snapshot['accounting_cost']
                                    )} ₽"
                                ),

                                fw=700,

                                size="lg",

                                c=TEXT,
                            ),
                        ],
                    ),

                    # ---------------------------------------------------------
                    # Управленческая стоимость
                    # ---------------------------------------------------------

                    html.Div(
                        children=[

                            dmc.Text(
                                "Управленческая с/с",

                                size="xs",

                                c="dimmed",
                            ),

                            dmc.Text(
                                (
                                    f"{fmt_money(
                                        snapshot['management_cost']
                                    )} ₽"
                                ),

                                fw=700,

                                size="lg",

                                c=TEXT,
                            ),
                        ],
                    ),
                ],
            ),

            # =================================================================
            # FOOTNOTE
            # =================================================================

            dmc.Text(
                (
                    "Оценка рассчитана только по товару, "
                    "физически находившемуся на складе "
                    "на конец дня, предшествующего происшествию; "
                    "позиции в пути не включены."
                ),

                size="xs",

                c="dimmed",

                mt="md",
            ),
        ],
    )


# =============================================================================
# ОСНОВНАЯ ПАНЕЛЬ
# =============================================================================


def build_incidents_panel():
    """
    Формирует блок происшествий на основной странице.

    Особенности:

    - события сортируются от новых к старым;
    - заголовок блока остаётся неподвижным;
    - прокручиваются только карточки событий;
    - при небольшом числе событий scroll не показывается;
    - при большом числе событий dashboard не растягивается вниз.
    """

    # =========================================================================
    # Собираем все события в единый список
    # =========================================================================

    events = []

    for warehouse_name, incidents in (
        WAREHOUSE_INCIDENTS.items()
    ):

        for incident in incidents:

            events.append(
                (
                    incident.get(
                        "date",
                        "",
                    ),

                    warehouse_name,

                    incident,
                )
            )

    # =========================================================================
    # Нет происшествий
    # =========================================================================

    if not events:
        return None

    # =========================================================================
    # Новые события сверху
    # =========================================================================

    events.sort(
        key=lambda item: item[0],

        reverse=True,
    )

    # =========================================================================
    # Панель
    # =========================================================================

    return dmc.Paper(
        radius=0,

        p="lg",

        style={
            "border": (
                f"1px solid {BORDER}"
            ),

            "background": "#FFFFFF",
        },

        children=[

            # =================================================================
            # HEADER
            #
            # Он находится СНАРУЖИ scroll-контейнера,
            # поэтому всегда остаётся видимым.
            # =================================================================

            dmc.Group(
                justify="space-between",

                align="flex-end",

                gap="md",

                mb="md",

                children=[

                    html.Div(
                        children=[

                            dmc.Text(
                                "Происшествия на складах",

                                fw=700,

                                size="md",

                                c=TEXT,
                            ),

                            dmc.Text(
                                (
                                    "Зафиксированные события и оценка "
                                    "физического товарного остатка "
                                    "на конец дня, предшествующего происшествию."
                                ),

                                size="xs",

                                c="dimmed",

                                mt=2,
                            ),
                        ],
                    ),

                    dmc.Group(
                        gap=8,

                        children=[

                            dmc.Badge(
                                (
                                    f"{len(events)} "
                                    f"{_event_word(len(events))}"
                                ),

                                color="red",

                                variant="light",

                                radius=0,
                            ),
                        ],
                    ),
                ],
            ),

            # =================================================================
            # SCROLL-КОНТЕЙНЕР
            #
            # Прокручиваются только карточки.
            # =================================================================

            html.Div(
                style={
                    "maxHeight": "520px",

                    "overflowY": "auto",

                    "overflowX": "hidden",

                    "paddingRight": "8px",

                    "scrollbarGutter": "stable",

                    # Safari
                    "WebkitOverflowScrolling": "touch",
                },

                children=[

                    dmc.Stack(
                        gap="sm",

                        children=[

                            _incident_card(
                                warehouse_name=warehouse_name,
                                incident=incident,
                            )

                            for (
                                _,
                                warehouse_name,
                                incident,
                            )
                            in events
                        ],
                    ),
                ],
            ),
        ],
    )


# =============================================================================
# СКЛОНЕНИЕ "СОБЫТИЕ / СОБЫТИЯ / СОБЫТИЙ"
# =============================================================================


def _event_word(
    count: int,
) -> str:
    """
    Возвращает правильное окончание:

    1 событие
    2 события
    5 событий
    21 событие
    23 события
    27 событий
    """

    count = abs(
        int(
            count
            or 0
        )
    )

    last_two = (
        count
        % 100
    )

    last_one = (
        count
        % 10
    )

    if (
        11
        <= last_two
        <= 14
    ):
        return "событий"

    if last_one == 1:
        return "событие"

    if last_one in {
        2,
        3,
        4,
    }:
        return "события"

    return "событий"