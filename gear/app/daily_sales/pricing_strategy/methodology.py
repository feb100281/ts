def methodology_rows() -> list[tuple]:
    """Плоский список (раздел, что, объяснение) — для Excel."""

    rows = []

    for section in methodology_sections():
        rows.append(
            (
                section["title"],
                "",
                section["lead"],
            )
        )

        for term, text in section["items"]:
            rows.append(
                (
                    "",
                    term,
                    text,
                )
            )

        if section["formula"]:
            rows.append(
                (
                    "",
                    "Формула",
                    section["formula"].replace("\n\n", " | ").replace("\n", " "),
                )
            )

        rows.append(("", "", ""))

    return rows


def methodology_text() -> str:
    """Простой текст — для README в zip."""

    lines = [
        "УПРАВЛЕНИЕ ЦЕНАМИ И МАРЖОЙ",
        "=" * 60,
        "",
    ]

    for section in methodology_sections():
        lines.append(section["title"].upper())
        lines.append("-" * 60)
        lines.append(section["lead"])
        lines.append("")

        for term, text in section["items"]:
            lines.append(f"  {term}: {text}")

        if section["formula"]:
            lines.append("")
            for formula_line in section["formula"].split("\n"):
                lines.append(f"  {formula_line}")

        lines.append("")

    return "\n".join(lines)
