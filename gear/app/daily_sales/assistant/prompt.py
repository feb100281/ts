_WD = ("понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье")


def _calendar() -> str:
    """Сегодняшняя дата с днём недели и готовые границы недель и месяцев."""
    from datetime import timedelta
    t = date.today()
    f = lambda d: d.strftime("%d.%m.%Y")
    mon = t - timedelta(days=t.weekday())                 # понедельник текущей недели
    weeks = []
    for k in range(1, 5):
        a = mon - timedelta(days=7 * k)
        weeks.append(f"{f(a)}–{f(a + timedelta(days=6))}")
    y = t - timedelta(days=1)
    this_m = t.replace(day=1)
    prev_m_end = this_m - timedelta(days=1)
    return (
        "КАЛЕНДАРЬ\n"
        f"Сегодня {f(t)}, {_WD[t.weekday()]}. Вчера — {f(y)}. Текущий год — {t.year}: "
        "месяц без года в вопросе относится к нему.\n"
        + ("Текущая неделя началась сегодня, завершённых дней в ней нет.\n" if y < mon
           else f"Текущая неделя (неполная): {f(mon)}–{f(y)}.\n") +
        "Завершённые недели, от последней: " + "; ".join(weeks) + ".\n" +
        ("Этот месяц начался сегодня. " if y < this_m
         else f"Этот месяц: {f(this_m)}–{f(y)}. ") +
        f"Прошлый месяц: {f(prev_m_end.replace(day=1))}–{f(prev_m_end)}.")


