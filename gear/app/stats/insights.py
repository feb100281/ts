def build_anomaly_insight(
    df: pd.DataFrame,
) -> str:
    """
    Формирует аналитический вывод
    по аномальным периодам продаж.
    """

    if df.empty:
        return (
            "За выбранный период выраженные "
            "аномальные периоды не обнаружены."
        )

    required_columns = {
        "period",
        "revenue",
        "anomaly_type",
        "marketing_change_pct",
        "revenue_change_pct",
        "price_change_pct",
        "quantity_change_pct",
    }

    if not required_columns.issubset(
        df.columns
    ):
        return (
            "Недостаточно данных "
            "для анализа аномальных периодов."
        )

    work = df.copy()

    # ================================================================
    # Подготовка данных
    # ================================================================

    work["period"] = pd.to_datetime(
        work["period"],
        errors="coerce",
    )

    numeric_columns = [
        "revenue",
        "marketing_change_pct",
        "revenue_change_pct",
        "price_change_pct",
        "quantity_change_pct",
    ]

    for column in numeric_columns:

        work[column] = pd.to_numeric(
            work[column],
            errors="coerce",
        )

    work = (
        work
        .replace(
            [
                np.inf,
                -np.inf,
            ],
            np.nan,
        )
        .dropna(
            subset=[
                "period",
                "revenue",
            ]
        )
        .sort_values(
            "period"
        )
        .reset_index(
            drop=True
        )
    )

    if work.empty:
        return (
            "За выбранный период выраженные "
            "аномальные периоды не обнаружены."
        )

    # ================================================================
    # Количество аномалий
    # ================================================================

    anomaly_count = len(
        work
    )

    positive = work[
        work[
            "revenue_change_pct"
        ] > 0
    ]

    negative = work[
        work[
            "revenue_change_pct"
        ] < 0
    ]

    positive_count = len(
        positive
    )

    negative_count = len(
        negative
    )

    # ================================================================
    # Максимальный рост
    # ================================================================

    best_row = None

    if not positive.empty:

        best_index = (
            positive[
                "revenue_change_pct"
            ]
            .idxmax()
        )

        best_row = work.loc[
            best_index
        ]

    # ================================================================
    # Максимальное падение
    # ================================================================

    worst_row = None

    if not negative.empty:

        worst_index = (
            negative[
                "revenue_change_pct"
            ]
            .idxmin()
        )

        worst_row = work.loc[
            worst_index
        ]

    # ================================================================
    # Неэффективный рост маркетинга
    #
    # Маркетинг вырос существенно,
    # а выручка не выросла
    # или снизилась.
    # ================================================================

    inefficient_marketing = work[
        (
            work[
                "marketing_change_pct"
            ] >= 20
        )
        &
        (
            work[
                "revenue_change_pct"
            ] <= 0
        )
    ]

    # ================================================================
    # Рост выручки без сопоставимого роста маркетинга
    # ================================================================

    organic_growth = work[
        (
            work[
                "revenue_change_pct"
            ] >= 20
        )
        &
        (
            (
                work[
                    "marketing_change_pct"
                ].isna()
            )
            |
            (
                work[
                    "marketing_change_pct"
                ] < 10
            )
        )
    ]

    # ================================================================
    # Рост выручки преимущественно за счёт количества
    # ================================================================

    quantity_driven = work[
        (
            work[
                "revenue_change_pct"
            ] > 0
        )
        &
        (
            work[
                "quantity_change_pct"
            ] > 0
        )
        &
        (
            work[
                "quantity_change_pct"
            ].abs()
            >
            work[
                "price_change_pct"
            ].abs()
        )
    ]

    # ================================================================
    # Рост выручки преимущественно за счёт цены
    # ================================================================

    price_driven = work[
        (
            work[
                "revenue_change_pct"
            ] > 0
        )
        &
        (
            work[
                "price_change_pct"
            ] > 0
        )
        &
        (
            work[
                "price_change_pct"
            ].abs()
            >
            work[
                "quantity_change_pct"
            ].abs()
        )
    ]

    # ================================================================
    # Формируем вывод
    # ================================================================

    parts = []

    # ------------------------------------------------
    # Общая картина
    # ------------------------------------------------

    parts.append(
        (
            f"За выбранный период обнаружено "
            f"{anomaly_count} аномальных наблюдений: "
            f"{positive_count} с необычно сильным ростом "
            f"выручки и {negative_count} "
            f"с выраженным снижением."
        )
    )

    # ------------------------------------------------
    # Максимальный рост
    # ------------------------------------------------

    if best_row is not None:

        best_date = (
            best_row[
                "period"
            ]
            .strftime(
                "%d.%m.%Y"
            )
        )

        parts.append(
            (
                f"Самая сильная положительная аномалия "
                f"зафиксирована {best_date}: "
                f"выручка изменилась на "
                f"{best_row['revenue_change_pct']:+.1f}%, "
                f"количество — на "
                f"{best_row['quantity_change_pct']:+.1f}%, "
                f"средняя цена — на "
                f"{best_row['price_change_pct']:+.1f}%, "
                f"маркетинг — на "
                f"{best_row['marketing_change_pct']:+.1f}%."
            )
        )

        # --------------------------------------------
        # Интерпретация максимального роста
        # --------------------------------------------

        quantity_change = (
            best_row[
                "quantity_change_pct"
            ]
        )

        price_change = (
            best_row[
                "price_change_pct"
            ]
        )

        if (
            pd.notna(
                quantity_change
            )
            and pd.notna(
                price_change
            )
        ):

            if (
                quantity_change > 0
                and abs(
                    quantity_change
                )
                >
                abs(
                    price_change
                )
            ):

                parts.append(
                    (
                        "Основным драйвером этого всплеска, "
                        "вероятно, был рост количества продаж, "
                        "а не изменение средней цены."
                    )
                )

            elif (
                price_change > 0
                and abs(
                    price_change
                )
                >
                abs(
                    quantity_change
                )
            ):

                parts.append(
                    (
                        "Рост выручки в этот период "
                        "в большей степени связан "
                        "с повышением средней цены."
                    )
                )

    # ------------------------------------------------
    # Максимальное падение
    # ------------------------------------------------

    if worst_row is not None:

        worst_date = (
            worst_row[
                "period"
            ]
            .strftime(
                "%d.%m.%Y"
            )
        )

        parts.append(
            (
                f"Наиболее сильное негативное отклонение "
                f"наблюдалось {worst_date}: "
                f"выручка изменилась на "
                f"{worst_row['revenue_change_pct']:+.1f}%, "
                f"количество — на "
                f"{worst_row['quantity_change_pct']:+.1f}%, "
                f"средняя цена — на "
                f"{worst_row['price_change_pct']:+.1f}%."
            )
        )

    # ------------------------------------------------
    # Неэффективный маркетинг
    # ------------------------------------------------

    if not inefficient_marketing.empty:

        parts.append(
            (
                f"Особого внимания требуют "
                f"{len(inefficient_marketing)} период(а), "
                f"в которых маркетинговые расходы выросли "
                f"не менее чем на 20%, "
                f"но выручка при этом не увеличилась. "
                f"Такие периоды стоит отдельно проверить "
                f"на эффективность рекламных кампаний."
            )
        )

    # ------------------------------------------------
    # Рост без маркетинга
    # ------------------------------------------------

    if not organic_growth.empty:

        parts.append(
            (
                f"В {len(organic_growth)} аномальном периоде(ах) "
                f"выручка выросла более чем на 20% "
                f"без сопоставимого роста маркетинговых расходов. "
                f"Возможными причинами могут быть органический спрос, "
                f"сезонность, изменение цены или структуры ассортимента."
            )
        )

    # ------------------------------------------------
    # Основной характер положительных аномалий
    # ------------------------------------------------

    if len(
        quantity_driven
    ) > len(
        price_driven
    ):

        parts.append(
            (
                "Среди положительных аномалий чаще встречается "
                "рост, связанный с увеличением количества продаж, "
                "чем с повышением средней цены."
            )
        )

    elif len(
        price_driven
    ) > len(
        quantity_driven
    ):

        parts.append(
            (
                "Среди положительных аномалий чаще встречаются "
                "периоды, в которых рост выручки сопровождается "
                "существенным повышением средней цены."
            )
        )

    # ------------------------------------------------
    # Методология
    # ------------------------------------------------

    parts.append(
        (
            "Аномалия означает статистически необычное наблюдение, "
            "но сама по себе не доказывает причинно-следственную связь. "
            "Для интерпретации конкретного периода следует одновременно "
            "учитывать маркетинг, изменение цены, количество продаж, "
            "сезонность, промоакции и изменение товарного микса."
        )
    )

    return " ".join(
        parts
    ) 
    
    
    
    
    
     